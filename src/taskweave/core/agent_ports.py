"""Persistence required by external AI use cases, without database dependencies."""

from typing import Any, Callable, Protocol


class AgentRecords(Protocol):
    def atomic(self, request_id: str, fingerprint: str, operation: Callable[[], Any]) -> Any: ...
    def claim(self, request_id: str, fingerprint: str) -> Any: ...
    def finish(self, request_id: str, fingerprint: str, result: Any) -> Any: ...
    def request(self, request_id: str) -> dict | None: ...
    def put(self, category: str, identity: str, value: Any) -> Any: ...
    def get(self, category: str, identity: str) -> Any: ...
    def find(self, category: str, limit: int = 100) -> list: ...
