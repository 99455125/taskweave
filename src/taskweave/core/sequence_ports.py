"""Persistence boundary for task-sequence definitions and executions."""

from typing import Any, Mapping, Protocol


class SequenceStore(Protocol):
    def save(self, name: str, nodes: list[dict[str, Any]], input_schema: Mapping[str, Any],
             description: str = "", sequence_id: str | None = None,
             expected_revision: int | None = None, flow: Mapping[str, Any] | None = None) -> dict[str, Any]: ...
    def get(self, sequence_id: str) -> dict[str, Any]: ...
    def list(self) -> list[dict[str, Any]]: ...
    def create_run(self, sequence_id: str, request_id: str, inputs: Mapping[str, Any],
                   task_hashes: Mapping[str, str], environment_hashes: Mapping[str, str],
                   plugin_versions: Mapping[str, str] | None = None,
                   expected_revision: int | None = None,
                   node_inputs: Mapping[str, Any] | None = None,
                   node_step_inputs: Mapping[str, Any] | None = None, *, mode: str = "EXECUTION") -> dict[str, Any]: ...
    def replay_start(self, sequence_id: str, request_id: str,
                     inputs: Mapping[str, Any], node_inputs: Mapping[str, Any] | None = None,
                     node_step_inputs: Mapping[str, Any] | None = None, *, mode: str = "EXECUTION") -> dict[str, Any] | None: ...
    def get_run(self, sequence_run_id: str) -> dict[str, Any]: ...
    def owner_of_child(self, run_id: str) -> tuple[str, str] | None: ...
