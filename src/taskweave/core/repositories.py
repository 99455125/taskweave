"""Narrow persistence ports used by application use cases."""

from typing import Any, Callable, ContextManager, Mapping, Protocol, Sequence
from taskweave.core.data_contracts import TaskRecord, StepRecord
from taskweave.core.run_ports import RunQueries, RunEvents, RunLeases, RunWrites, LegacyRunResults


class UnitOfWork(Protocol):
    def transaction(self) -> ContextManager[Any]: ...


class TaskRepository(Protocol):
    def create_task(self, name: str, input_schema: Mapping[str, Any] | None = None, description: str = "") -> TaskRecord: ...
    def task(self, task_id: str) -> TaskRecord: ...
    def definition_hash(self, task_id: str) -> str: ...
    def list_tasks(self) -> Sequence[TaskRecord]: ...
    def update_task(self, task_id: str, name: str, input_schema: Mapping[str, Any], description: str = "") -> TaskRecord: ...
    def delete_task(self, task_id: str) -> Mapping[str, Any]: ...
    def copy_task(self, task_id: str, name: str | None = None) -> TaskRecord: ...


class StepRepository(Protocol):
    def step(self, step_id: str) -> StepRecord: ...
    def steps(self, task_id: str) -> Sequence[StepRecord]: ...
    def save_step(self, task_id: str, document: Mapping[str, Any], step_id: str | None = None, expected_hash: str | None = None) -> StepRecord: ...
    def reorder(self, task_id: str, step_ids: Sequence[str]) -> Sequence[Mapping[str, Any]]: ...
    def delete_step(self, step_id: str) -> Mapping[str, Any]: ...
    def confirm(self, step_id: str, attempt_id: str, expected_hash: str) -> Mapping[str, Any]: ...
    def confirm_manual(self, step_id: str, expected_hash: str, environment_id: str | None = None) -> Mapping[str, Any]: ...
    def confirm_imported(self, step_id: str, expected_hash: str) -> Mapping[str, Any]: ...


class EnvironmentRepository(Protocol):
    def save_environment(self, name: str, public_config: Mapping[str, Any], secret_refs: Mapping[str, str] | None = None, environment_id: str | None = None, descriptions: Mapping[str, str] | None = None) -> Mapping[str, Any]: ...
    def environment(self, environment_id: str | None) -> tuple[Mapping[str, Any], Mapping[str, str]]: ...
    def list_environments(self) -> Sequence[Mapping[str, Any]]: ...
    def delete_environment(self, environment_id: str) -> Mapping[str, Any]: ...


class RunRepository(RunQueries, RunEvents, RunLeases, RunWrites, LegacyRunResults, Protocol):
    """Compatibility aggregate; new consumers use responsibility-specific ports."""



class ResultRepository(Protocol):
    def read_output(self, run_id: str, step_id: str, output: str = "data", registry: Any = None) -> Any: ...
    def read_result(self, result_id: str, registry: Any) -> Any: ...
    def delete_result(self, result_id: str) -> Mapping[str, Any]: ...
    def receipt(self, attempt: Mapping[str, Any]) -> Sequence[Mapping[str, Any]] | None: ...
    def refs_for_attempt(self, attempt_id: str) -> Sequence[Mapping[str, Any]]: ...


class StepContextRepository(Protocol):
    def list_step_contexts(self, step_id: str) -> Sequence[Mapping[str, Any]]: ...
    def get_step_context_capture(self, context_id: str, capture_id: str, step_id: str | None = None) -> Mapping[str, Any]: ...
    def step_context_records(self, step_id: str) -> Sequence[Mapping[str, Any]]: ...
    def create_step_context_group(self, step_id: str, provider_id: str, name: str, context_notes: str = "") -> Mapping[str, Any]: ...
    def save_step_context_batch(self, step_id: str, context_id: str | None, expected_revision: int | None, provider_id: str, name: str, context_notes: str, captures: Sequence[Mapping[str, Any]]) -> Mapping[str, Any]: ...
    def update_step_context_group(self, step_id: str, context_id: str, name: str, context_notes: str = "", expected_revision: int | None = None) -> Mapping[str, Any]: ...
    def save_step_context(self, step_id: str, provider_id: str, name: str, source_page: str, item: Any, context_id: str | None = None, context_notes: str = "", request: Mapping[str, Any] | None = None, views: Sequence[Mapping[str, Any]] | None = None, include_view: bool = True, replace_capture: bool = False, captured_at: str | None = None, capture_id: str | None = None, append: bool = False, expected_revision: int | None = None, source_session_id: str | None = None) -> Mapping[str, Any]: ...
    def append_step_context_capture(self, context_id: str, capture: Mapping[str, Any], *, request: Mapping[str, Any] | None = None, include_view: bool = True, source_page: str = "draft", source_session_id: str | None = None, label: str = "", captured_at: str | None = None, expected_revision: int | None = None, step_id: str | None = None) -> Mapping[str, Any]: ...
    def replace_step_context_capture(self, context_id: str, capture_id: str, capture: Mapping[str, Any], *, request: Mapping[str, Any] | None = None, include_view: bool = True, source_page: str = "draft", source_session_id: str | None = None, label: str | None = None, captured_at: str | None = None, expected_revision: int | None = None, step_id: str | None = None) -> Mapping[str, Any]: ...
    def update_step_context_capture_label(self, context_id: str, capture_id: str, label: str, expected_revision: int | None = None, step_id: str | None = None, operation_notes: str | None = None, send_preview: bool | None = None) -> Sequence[Mapping[str, Any]]: ...
    def reorder_step_context(self, context_id: str, direction: str, expected_revision: int | None = None, step_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...
    def delete_step_context_capture(self, context_id: str, capture_id: str, expected_revision: int | None = None, step_id: str | None = None) -> Mapping[str, Any]: ...
    def reorder_step_context_capture(self, context_id: str, capture_id: str, direction: str, expected_revision: int | None = None, step_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...
    def delete_step_context(self, context_id: str, expected_revision: int | None = None, step_id: str | None = None) -> Mapping[str, Any]: ...


class PlanRepositoryPort(Protocol):
    def create(self, name: str = "新计划") -> Mapping[str, Any]: ...
    def copy(self, plan_id: str, expected_revision: int) -> Mapping[str, Any]: ...
    def list(self) -> Sequence[Mapping[str, Any]]: ...
    def get(self, plan_id: str) -> Mapping[str, Any]: ...
    def update(self, plan_id: str, expected_revision: int, name: str, plan_description: str = "", plan_notes: str = "", environment_id: str | None = None, plugin_ids: Sequence[str] | None = None) -> Mapping[str, Any]: ...
    def delete(self, plan_id: str, expected_revision: int) -> Mapping[str, Any]: ...


class PlanContextRepository(Protocol):
    def contexts(self, plan_id: str) -> Sequence[Mapping[str, Any]]: ...
    def get_capture(self, context_id: str, capture_id: str, plan_id: str | None = None) -> Mapping[str, Any]: ...
    def context_records(self, plan_id: str) -> Sequence[Mapping[str, Any]]: ...
    def add_context(self, plan_id: str, expected_revision: int, provider_id: str, name: str, context_notes: str, session_id: str, items: Sequence[Any], request: Mapping[str, Any] | None = None, views: Sequence[Mapping[str, Any]] | None = None, include_view: bool = True) -> Mapping[str, Any]: ...
    def update_context(self, plan_id: str, expected_revision: int, context_id: str, name: str, context_notes: str = "") -> Mapping[str, Any]: ...
    def replace_context(self, plan_id: str, expected_revision: int, context_id: str, provider_id: str, name: str, context_notes: str, session_id: str, items: Sequence[Any], request: Mapping[str, Any] | None = None, views: Sequence[Mapping[str, Any]] | None = None, include_view: bool = True) -> Mapping[str, Any]: ...
    def save_context_batch(self, plan_id: str, expected_revision: int, context_id: str | None, provider_id: str, name: str, context_notes: str, captures: Sequence[Mapping[str, Any]]) -> Mapping[str, Any]: ...
    def append_capture(self, plan_id: str, expected_revision: int, context_id: str, capture: Mapping[str, Any], *, request: Mapping[str, Any] | None = None, include_view: bool = True, session_id: str | None = None, label: str = "") -> Mapping[str, Any]: ...
    def delete_context(self, plan_id: str, expected_revision: int, context_id: str) -> Mapping[str, Any]: ...
    def reorder_context(self, plan_id: str, expected_revision: int, context_id: str, direction: str) -> Mapping[str, Any]: ...
    def replace_capture(self, plan_id: str, expected_revision: int, context_id: str, capture_id: str, capture: Mapping[str, Any], *, request: Mapping[str, Any] | None = None, include_view: bool = True, session_id: str | None = None) -> Mapping[str, Any]: ...
    def update_capture_label(self, plan_id: str, expected_revision: int, context_id: str, capture_id: str, label: str, operation_notes: str | None = None, send_preview: bool | None = None) -> Mapping[str, Any]: ...
    def delete_capture(self, plan_id: str, expected_revision: int, context_id: str, capture_id: str) -> Mapping[str, Any]: ...
    def reorder_capture(self, plan_id: str, expected_revision: int, context_id: str, capture_id: str, direction: str) -> Mapping[str, Any]: ...


class PlanGenerationRepository(Protocol):
    def create_generation(self, plan_id: str, revision: int, channel: str, request_path: str) -> Mapping[str, Any]: ...
    def generation(self, generation_id: str) -> Mapping[str, Any]: ...
    def generations(self, plan_id: str) -> Sequence[Mapping[str, Any]]: ...
    def imports(self, generation_id: str) -> Sequence[Mapping[str, Any]]: ...
    def finish_generation(self, generation_id: str, status: str, response_path: str | None = None, candidate: Mapping[str, Any] | None = None, diagnostics: Sequence[Any] | None = None) -> Mapping[str, Any]: ...
    def mark_imported(self, generation_id: str, task_id: str) -> Mapping[str, Any]: ...


class OrganizationRepository(Protocol):
    def categories(self) -> Sequence[Mapping[str, Any]]: ...
    def create_category(self, name: str) -> Mapping[str, Any]: ...
    def rename_category(self, category_id: str, name: str) -> Mapping[str, Any]: ...
    def delete_category(self, category_id: str) -> Mapping[str, Any]: ...
    def set_metadata(self, entity: str, entity_id: str, is_favorite: bool, category_id: str | None) -> Mapping[str, Any]: ...
